#!/usr/bin/env python3
"""
scripts/third_party_notices.py — THIRD_PARTY_LICENSES.md, generated from the three
lockfiles, so the list cannot drift from what ships
(.agent-rfc/designs/agpl-compliance.md).

Python licences come from installed package metadata, so run it in an environment
built from requirements.lock. npm licences come from the lockfiles.
scripts/test/test_agpl_compliance.py holds the result against the lockfiles and the
reviewed licences below.
"""

from __future__ import annotations

import importlib.metadata as metadata
import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUTPUT = REPO / "THIRD_PARTY_LICENSES.md"
NPM_LOCKS = {
    "Ops Portal (portal/)": "portal/package-lock.json",
    "In-app widget (templates/in-app-widget/)": "templates/in-app-widget/package-lock.json",
}

# npm's lockfile leaves these blank; each package's own LICENSE file says MIT.
NPM_LICENSE_GAPS = {"busboy": "MIT", "streamsearch": "MIT"}

# Pinned for another platform or Python version, so not installed where this runs.
PLATFORM_ONLY = {
    "async-timeout": "Apache-2.0",
    "colorama": "BSD-3-Clause",
    "tzdata": "Apache-2.0",
    "httpx2-jsfetch": "BSD-3-Clause",
}


def pinned_python() -> dict[str, str]:
    lock = (REPO / "requirements.lock").read_text(encoding="utf-8")
    return dict(re.findall(r"^([A-Za-z0-9_.-]+)==([^ \\\n]+)", lock, re.M))


def pinned_npm(lock: str) -> dict[str, tuple[str, str]]:
    packages = json.loads((REPO / lock).read_text(encoding="utf-8")).get("packages", {})
    found: dict[str, tuple[str, str]] = {}
    for path, meta in packages.items():
        if path:
            name = path.rsplit("node_modules/", 1)[-1]
            licence = meta.get("license") or NPM_LICENSE_GAPS.get(name, "UNKNOWN")
            found[name] = (str(meta.get("version", "")), str(licence))
    return found


def python_license(name: str) -> str:
    try:
        data = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return PLATFORM_ONLY.get(name, "UNKNOWN")
    if data.get("License-Expression"):
        return data["License-Expression"]
    classifiers = [c.split("::")[-1].strip() for c in (data.get_all("Classifier") or []) if c.startswith("License ::")]
    return " / ".join(classifiers) or (data.get("License") or "UNKNOWN").split("\n")[0][:60]


def render() -> str:
    lines = [
        "# Third-party licences",
        "",
        "Generated by `scripts/third_party_notices.py` from the lockfiles; do not edit by hand. AgentSmith",
        "itself is AGPL-3.0-only: see `LICENSE` and `NOTICE`.",
        "",
        "Each package keeps its own licence. `docker-compose.yml` also starts separately licensed",
        "services that are not combined with AgentSmith: Arize Phoenix (Elastic License 2.0, which",
        "restricts offering it as a hosted or managed service) and PostgreSQL (PostgreSQL License).",
        "",
    ]
    lines += ["## Python (`requirements.lock`)", "", "| Package | Version | Licence |", "|---|---|---|"]
    for name, version in sorted(pinned_python().items()):
        lines.append(f"| {name} | {version} | {python_license(name)} |")
    for title, lock in NPM_LOCKS.items():
        lines += ["", f"## {title}", "", "| Package | Version | Licence |", "|---|---|---|"]
        for name, (version, licence) in sorted(pinned_npm(lock).items()):
            lines.append(f"| {name} | {version} | {licence} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO)}")
